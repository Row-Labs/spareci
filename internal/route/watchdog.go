package route

import (
	"bytes"
	"cmp"
	"fmt"
	"strconv"
	"strings"
	"text/template"
)

// WatchdogSecret holds a token that can delete repo variables: the manual
// fallback to the app that `spareci watchdog --setup` creates. The workflow's
// own GITHUB_TOKEN can cancel and re-run, but GitHub doesn't let it write
// variables.
const WatchdogSecret = "SPARECI_TOKEN"

// Secrets holding the watchdog app's client ID and private key (ghapp writes
// them; the names live here so the workflow doesn't import ghapp).
const (
	AppClientIDSecret = "SPARECI_APP_CLIENT_ID"
	AppKeySecret      = "SPARECI_APP_KEY"
)

// Watchdog renders the workflow that routes jobs back to GitHub-hosted runners
// when a machine dies without cleaning up (crash, kill -9, power loss, a
// sleeping laptop). It runs on GitHub-hosted runners, because by then nothing
// on the machine can. groups are every routing group (AllGroups); each is
// checked against its own heartbeat, so only a dead machine's variables are
// cleared.
func Watchdog(groups []Group) string {
	var crons []string
	for _, m := range Slots() {
		crons = append(crons, Cron(m))
	}
	type tg struct {
		Key, Name, Heartbeat string
		Vars                 []string
		Beat                 string // the heartbeat as an expression
		Shell                string // and in the shell
	}
	old := ""
	for _, g := range groups {
		if g.Legacy() {
			old = g.Heartbeat
		}
	}
	var gs []tg
	for _, g := range groups {
		if g.Heartbeat == "" {
			continue
		}
		// spareci 0.2 sets the per-OS variables with only the old heartbeat:
		// an OS without a heartbeat of its own reads that one, so this
		// workflow can be merged before the machines are upgraded.
		t := tg{Key: strings.ToLower(cmp.Or(g.OS, "legacy")), Name: g.Name(), Heartbeat: g.Heartbeat,
			Beat: "vars." + g.Heartbeat, Shell: "$" + g.Heartbeat}
		if !g.Legacy() && old != "" {
			t.Beat = "(vars." + g.Heartbeat + " || vars." + old + ")"
			t.Shell = "${" + g.Heartbeat + ":-$" + old + "}"
		}
		for _, rt := range g.Routes {
			t.Vars = append(t.Vars, rt.Var)
		}
		gs = append(gs, t)
	}
	// Skipped, and not billed, unless some group has a variable set and a
	// heartbeat that doesn't list this firing.
	var cond []string
	for _, g := range gs {
		var vars []string
		for _, v := range g.Vars {
			vars = append(vars, "vars."+v)
		}
		cond = append(cond, fmt.Sprintf("((%s) && !contains(%s, format('|{0}|', github.event.schedule)))",
			strings.Join(vars, " || "), g.Beat))
	}
	var b bytes.Buffer
	err := watchdogTmpl.Execute(&b, map[string]any{
		"Crons":  crons,
		"Groups": gs,
		"Cond":   strings.Join(cond, " || "),
		"Secret": WatchdogSecret,
		"AppID":  AppClientIDSecret,
		"AppKey": AppKeySecret,
		"Stale":  int(StaleAfter.Seconds()),
		"Behind": int(LeaseBehind.Minutes()),
	})
	if err != nil {
		panic(err)
	}
	return b.String()
}

var watchdogTmpl = template.Must(template.New("watchdog").Delims("<%", "%>").Funcs(template.FuncMap{
	// Double quotes, as Prettier writes YAML strings, so the file passes
	// prettier --check unchanged (testdata/spareci-watchdog.yml).
	"q":     func(s string) string { return strconv.Quote(s) },
	"upper": strings.ToUpper,
	"env": func(vars []string) string {
		var parts []string
		for _, v := range vars {
			parts = append(parts, "$"+v)
		}
		return strings.Join(parts, "")
	},
}).Parse(`# Generated by ` + "`spareci watchdog`" + `. Keep it on the default branch.
#
# If a machine running spareci dies without ^C (crash, kill -9, power loss,
# a sleeping laptop), this clears its routing variables so new runs go to
# GitHub-hosted runners, and cancels and re-runs jobs already queued for
# that machine. Each OS has its own heartbeat, written by the machine that
# serves it, so only a dead machine's variables are cleared. An OS without
# its own heartbeat (from spareci 0.2) reads the last one:
<%- range .Groups%>
#   <%.Heartbeat%>: <%range $i, $v := .Vars%><%if $i%>, <%end%><%$v%><%end%>
<%- end%>
#
# Cost: while spareci is healthy, its heartbeats list the upcoming firings
# below and each one is skipped, which uses no Actions minutes. It runs for
# real (about one minute) when a heartbeat is older than <%.Stale%>s, or when
# GitHub starts a firing more than <%.Behind%> minutes late.
#
# Setup: run spareci watchdog --setup. It creates a private GitHub App with
# one permission (Variables: read and write), installs it on this repo and
# stores <%.AppID%> and <%.AppKey%>. Each run mints an hour-long
# token from them, so nothing expires.
# Fallback: a fine-grained token for this repo with "Variables: read and
# write", saved as the <%.Secret%> secret: gh secret set <%.Secret%>
name: spareci watchdog

on:
  schedule:
<%- range .Crons%>
    - cron: <%q .%>
<%- end%>
  workflow_dispatch:

permissions:
  actions: write

concurrency:
  group: spareci-watchdog

jobs:
  watchdog:
    if: <%.Cond%>
    runs-on: ubuntu-latest
    timeout-minutes: 10
    env:
      HAS_APP: ${{ secrets.<%.AppID%> != '' }}
<%- range .Groups%>
      <%.Heartbeat%>: ${{ vars.<%.Heartbeat%> }}
<%- range .Vars%>
      <%.%>: ${{ vars.<%.%> }}
<%- end%>
<%- end%>
    steps:
      - name: Check the heartbeats
        id: beat
        run: |
          now=$(date +%s)
          # check <name> <key> <heartbeat> <routing variables, empty if none is set>
          check() {
            [ -n "$4" ] || return 0
            local beat=${3%%|*} who=${3##*|}
            if [ -z "$who" ] || [ "$who" = "$3" ]; then who="spareci"; fi
            if [[ "$beat" =~ ^[0-9]+$ ]] && (( now - beat < <%.Stale%> )); then
              echo "$1: $who is up, last heartbeat $(( now - beat ))s ago"
            elif [[ "$beat" =~ ^[0-9]+$ ]]; then
              echo "$1: no heartbeat from $who for $(( now - beat ))s: routing its jobs to GitHub-hosted runners"
              echo "$2=true" >> "$GITHUB_OUTPUT"
              echo stale=true >> "$GITHUB_OUTPUT"
            else
              echo "$1: routed with no heartbeat: routing its jobs to GitHub-hosted runners"
              echo "$2=true" >> "$GITHUB_OUTPUT"
              echo stale=true >> "$GITHUB_OUTPUT"
            fi
          }
<%- range .Groups%>
          check <%.Name%> <%.Key%> "<%.Shell%>" "<%env .Vars%>"
<%- end%>

      - name: Mint a token that can write variables
        id: app
        # If this fails (app uninstalled, key revoked), fall back to <%.Secret%>.
        continue-on-error: true
        if: steps.beat.outputs.stale == 'true' && env.HAS_APP == 'true'
        uses: actions/create-github-app-token@v3
        with:
          client-id: ${{ secrets.<%.AppID%> }}
          private-key: ${{ secrets.<%.AppKey%> }}

      - name: Route a dead machine's jobs back to GitHub
        if: steps.beat.outputs.stale == 'true'
        env:
          GH_TOKEN: ${{ github.token }}
          VAR_TOKEN: ${{ steps.app.outputs.token || secrets.<%.Secret%> }}
          REPO: ${{ github.repository }}
<%- range .Groups%>
          STALE_<%upper .Key%>: ${{ steps.beat.outputs.<%.Key%> }}
<%- end%>
        run: |
          set -euo pipefail
          if [ -z "$VAR_TOKEN" ]; then
            echo "::error::No token can write repo variables. Run spareci watchdog --setup, or add a token as the <%.Secret%> secret (see this file's header)"
            exit 1
          fi
          labels=()
          unroute() {
            if [ -n "$2" ]; then
              GH_TOKEN=$VAR_TOKEN gh api -X DELETE "repos/$REPO/actions/variables/$1"
              labels+=("$2")
            fi
          }
<%- range .Groups%>
          if [ "$STALE_<%upper .Key%>" = true ]; then
<%- range .Vars%>
            unroute <%.%> "$<%.%>"
<%- end%>
            GH_TOKEN=$VAR_TOKEN gh api -X DELETE "repos/$REPO/actions/variables/<%.Heartbeat%>" || true
          fi
<%- end%>
          if [ ${#labels[@]} -eq 0 ]; then exit 0; fi

          # Runs read variables when they start, so jobs already queued for the
          # machine stay queued. Cancel and re-run them: the re-run reads the
          # cleared variables and goes to GitHub-hosted runners. Jobs routed to
          # a machine that's still up keep its variable and go back to it.
          ls=$(printf '%s\n' "${labels[@]}" | tr '[:upper:]' '[:lower:]' | jq -R . | jq -sc .)
          here='any(.labels[]; ascii_downcase | IN($ls[]))'

          cancel() {
            gh api -X POST "repos/$REPO/actions/runs/$1/cancel" >/dev/null || true
            for i in $(seq 1 40); do
              [ "$(gh api "repos/$REPO/actions/runs/$1" --jq .status)" = completed ] && return
              if [ "$i" = 20 ]; then gh api -X POST "repos/$REPO/actions/runs/$1/force-cancel" >/dev/null || true; fi
              sleep 3
            done
          }

          runs=$(for s in queued in_progress; do
            gh api "repos/$REPO/actions/runs?status=$s&per_page=100" --jq '.workflow_runs[].id'
          done | sort -u)
          for run in $runs; do
            [ "$run" = "$GITHUB_RUN_ID" ] && continue
            jobs=$(gh api "repos/$REPO/actions/runs/$run/jobs?filter=latest&per_page=100")
            stuck=$(jq --argjson ls "$ls" "[.jobs[] | select(.status == \"queued\" and ($here))] | length" <<<"$jobs")
            [ "$stuck" -gt 0 ] || continue
            # A job that already finished on the machine saved its caches there,
            # where a hosted re-run of a later job can't restore them: re-run
            # the whole run in that case.
            done_here=$(jq --argjson ls "$ls" "[.jobs[] | select(.status == \"completed\" and .conclusion != \"cancelled\" and .conclusion != \"skipped\" and ($here))] | length" <<<"$jobs")
            rerun=rerun-failed-jobs
            [ "$done_here" -gt 0 ] && rerun=rerun
            echo "run $run: $stuck job(s) queued for spareci; cancelling, then $rerun"
            cancel "$run"
            if ! gh api -X POST "repos/$REPO/actions/runs/$run/$rerun" >/dev/null; then
              echo "::warning::could not re-run run $run"
              continue
            fi
            [ "$rerun" = rerun ] && continue
            # GitHub has been seen to leave a cancelled job out of a failed-jobs
            # re-run. If it did, cancel the new attempt and re-run everything.
            sleep 10
            # Such a job is listed under the new attempt but finished before it began.
            started=$(gh api "repos/$REPO/actions/runs/$run" --jq .run_started_at)
            left=$(gh api "repos/$REPO/actions/runs/$run/jobs?filter=latest&per_page=100" |
              jq --arg s "$started" '[.jobs[] | select(.conclusion == "cancelled" and .completed_at < $s)] | length')
            if [ "$left" -gt 0 ]; then
              echo "run $run: re-run left $left cancelled job(s) out; re-running the whole run"
              cancel "$run"
              gh api -X POST "repos/$REPO/actions/runs/$run/rerun" >/dev/null ||
                echo "::warning::could not re-run run $run"
            fi
          done
`))
